// Renders tpl/<page>.md -> <ROOT>/knowledge/reference/<page>.md replacing {{gen:module.table}} tokens.
// Also expands bare file names in backticks inside "## Sources" to full paths that exist on disk.
const fs = require('fs');
const path = require('path');
const L = require('./lib.cjs');
const mods = {
  classes: require('./gen_classes.cjs'), items: require('./gen_items.cjs'), uniques: require('./gen_uniques.cjs'),
  idols: require('./gen_idols.cjs'), misc: require('./gen_misc.cjs'), glossary: require('./gen_glossary.cjs')
};
const FILE = { classes: 'gen_classes.cjs', items: 'gen_items.cjs', uniques: 'gen_uniques.cjs', idols: 'gen_idols.cjs', misc: 'gen_misc.cjs', glossary: 'gen_glossary.cjs' };
const tplDir = path.join(__dirname, 'tpl');
const outDir = path.join(L.ROOT, 'knowledge/reference');
fs.mkdirSync(outDir, { recursive: true });
const CORPUS = 'C:\\Users\\Genesis\\AppData\\Local\\Temp\\claude\\D--src-last-epoch-assistant\\2a02c54d-b8b3-416e-bc0a-3ef48c1c23fd\\scratchpad\\corpus';
const V = 'vendor/lastepochbuilder/research';
const SEARCH = [
  [null, CORPUS],
  [V, path.join(L.ROOT, V)],
  [V + '/data', path.join(L.ROOT, V, 'data')],
  [V + '/data/game', path.join(L.ROOT, V, 'data/game')],
  [V + '/02_assets', path.join(L.ROOT, V, '02_assets')]
];
function expandSources(text) {
  const i = text.indexOf('\n## Sources');
  if (i < 0) return text;
  const head = text.slice(0, i);
  let tail = text.slice(i);
  tail = tail.replace(/`([^`\\/]+\.(md|txt|json))`/g, (m, name) => {
    for (const [pre, dir] of SEARCH) {
      if (fs.existsSync(path.join(dir, name))) return '`' + (pre === null ? CORPUS + '\\' + name : pre + '/' + name) + '`';
    }
    return m;
  });
  return head + tail;
}
const log = [];
const only = process.argv[2];
for (const tf of fs.readdirSync(tplDir).filter(x => x.endsWith('.md.tpl'))) {
  const f = tf.replace(/\.tpl$/, '');
  if (only && f !== only + '.md') continue;
  let t = fs.readFileSync(path.join(tplDir, tf), 'utf8');
  const used = new Set();
  t = t.replace(/\{\{gen:([a-z_]+)\.([a-z_0-9]+)\}\}/g, (m, mod, name) => {
    const g = mods[mod] && mods[mod][name];
    if (!g || !g.fn) throw new Error(`missing generator ${mod}.${name} in ${f}`);
    const r = g.fn();
    used.add(FILE[mod]);
    log.push({ page: f.replace('.md', ''), table: `${mod}.${name}`, script: FILE[mod], source: g.src, rows: r.rows });
    return r.md + `\n\n<sub>Generated by \`${FILE[mod]}\` (table \`${name}\`) from ${g.src}; ${r.rows} rows.</sub>`;
  });
  t = expandSources(t);
  const NL = String.fromCharCode(10);
  if (used.size) t = t.replace(/\s*$/, NL) + '- ' + [...used].map(u => '`knowledge/reference/_gen/' + u + '`').join(', ') + ', `knowledge/reference/_gen/lib.cjs`, `knowledge/reference/_gen/build.cjs` - generators of every table marked "Generated by" on this page (run `node knowledge/reference/_gen/build.cjs`).' + NL;
  fs.writeFileSync(path.join(outDir, f), t.replace(/\r\n/g, '\n'));
  console.log(f, t.split('\n').length, 'lines');
}
if (!only) fs.writeFileSync(path.join(__dirname, 'generated_tables.json'), JSON.stringify(log, null, 1));
